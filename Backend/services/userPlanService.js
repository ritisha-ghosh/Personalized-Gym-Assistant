// ─── ML WORKOUT FETCH ────────────────────────────────────────────────────────

const getMLWorkoutRecommendation = async (user) => {
  try {
    const response = await axios.post(`${ML_API_URL}/recommend-plan`, {
      age:              Number(user.age)    || 25,
      weight_kg:        Number(user.weight) || 70,
      experience_level: experienceMap[normalizeExperience(user.experience)] || 2,
      goal_type:        goalMap[normalizeGoal(user.goal)] || 3,
      disease:  (user.medicalConditions && user.medicalConditions.length > 0) ? user.medicalConditions.join(' ') : 'none',
      injury:   (user.injuries          && user.injuries.length          > 0) ? user.injuries.join(' ')          : 'none',
      exhausted_muscles: []
    }, { timeout: 6000 });

    const data = response.data;
    if (!data) throw new Error('Empty ML response');

    return {
      recommendationId: data.recommended_cluster_index || null,
      routine:          data.base_routine               || null,
      planMeta:         data.medical_mutations_applied  || null
    };
  } catch (error) {
    console.warn('Workout plan recommendation service unavailable:', error.message || error);
    return { recommendationId: null, routine: null, planMeta: null };
  }
};

// ─── MUSCLE INFERENCE ────────────────────────────────────────────────────────

const inferMuscleGroup = (text) => {
  const lower = String(text || '').toLowerCase();
  if (/chest|pec|bench/.test(lower))                              return 'chest';
  if (/back|row|pull|lat/.test(lower))                            return 'back';
  if (/shoulder|press|overhead|lateral/.test(lower))              return 'shoulders';
  if (/bicep|curl/.test(lower))                                   return 'biceps';
  if (/tricep|dip|pushdown/.test(lower))                          return 'triceps';
  if (/squat|quad|leg|lunge|press/.test(lower))                   return 'quads';
  if (/deadlift|hamstring|romanian|glute/.test(lower))            return 'hamstrings';
  if (/calf|heel/.test(lower))                                    return 'calves';
  if (/core|plank|crunch|twist|ab|sit-up/.test(lower))            return 'core';
  if (/yoga|stretch|mobility|walking|jog|cycle|run/.test(lower))  return 'full body';
  return 'full body';
};

// ─── BUILD WEEKLY WORKOUT PLAN ───────────────────────────────────────────────

const buildWeeklyWorkoutPlan = (user, routineDict, planMeta, difficultyCoefficient = 1.0) => {
  const goal       = normalizeGoal(user.goal);
  const experience = normalizeExperience(user.experience);

  let baseSets = 3;
  let baseReps = 12;
  if (experience === 'beginner') { baseSets = 2; baseReps = 15; }
  if (experience === 'advanced') { baseSets = 4; baseReps = 8;  }

  const days = ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday'];

  return days.map((dayName, idx) => {
    const rawExercises = (routineDict && routineDict[dayName]) ? routineDict[dayName] : 'Push Ups, Squats, Planks';
    const isRestDay    = rawExercises.toLowerCase() === 'rest' || rawExercises.toLowerCase().includes('rest day');

    let parsedExercises = [];
    let focusMuscles    = new Set();

    if (!isRestDay) {
      parsedExercises = rawExercises.split(',').map((ex, i) => {
        const cleanName = ex.trim();
        const muscle    = inferMuscleGroup(cleanName);
        focusMuscles.add(muscle);

        let dynamicSets = baseSets;
        let dynamicReps = baseReps;

        if (i === 0) {
          dynamicSets = Math.max(baseSets, 3);
          dynamicReps = Math.min(baseReps, 8);
        } else if (goal === 'fat loss') {
          dynamicReps = 15;
        } else if (goal === 'muscle gain') {
          dynamicSets = Math.min(baseSets + 1, 5);
          dynamicReps = 10;
        }

        if (muscle === 'core' || muscle === 'calves') {
          dynamicReps = 15 + Math.floor(Math.random() * 6);
        }

        dynamicSets = Math.max(1, Math.round(dynamicSets * difficultyCoefficient));
        dynamicReps = Math.max(1, Math.round(dynamicReps * difficultyCoefficient));

        return {
          name:        cleanName,
          sets:        dynamicSets,
          reps:        dynamicReps,
          muscleGroup: muscle
        };
      });
    }

    const title = isRestDay ? 'Rest & Recovery' : `${dayName} Training`;

    let medicalNotes = '';
    if (planMeta && planMeta.length > 0) {
      medicalNotes = `Medical Protocol Active: ${planMeta.join(' ')}`;
    } else if (goal === 'fat loss') {
      medicalNotes = 'Keep rest periods short (45s) to maintain elevated heart rate.';
    } else if (goal === 'muscle gain') {
      medicalNotes = 'Focus on eccentric control. Rest 90-120s between heavy sets.';
    }

    const weekStart = getMondayStart();
    const date      = new Date(weekStart);
    date.setDate(date.getDate() + idx);
    const isoDate   = `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, '0')}-${String(date.getDate()).padStart(2, '0')}`;
    const today     = new Date();
    today.setHours(0, 0, 0, 0);

    return {
      date:               isoDate,
      dayName:            title === 'Rest & Recovery' ? 'Rest Day' : date.toLocaleDateString('en-US', { weekday: 'long' }),
      isToday:            isoDate === today.toISOString().slice(0, 10),
      dayIndex:           idx,
      title,
      type:               isRestDay ? 'rest' : 'strength',
      focusMuscles:       isRestDay ? ['rest'] : Array.from(focusMuscles),
      exercises:          parsedExercises,
      notes:              medicalNotes,
      completed:          false,
      completedExercises: [],
      difficultyRating:   null
    };
  });
};

// ─── GENERATE & SAVE WORKOUT ─────────────────────────────────────────────────

const generateAndSaveWorkoutPlan = async (user) => {
  const mlRecommendation = await getMLWorkoutRecommendation(user);

  console.log('==== ML WORKOUT DEBUG ====');
  console.log('Full ML response:', mlRecommendation);
  console.log('==========================');

  const weeklyPlan = buildWeeklyWorkoutPlan(
    user,
    mlRecommendation.routine,
    mlRecommendation.planMeta,
    1.0
  );

  const filter  = { user: user._id, isAutoGenerated: true };

  const payload = {
    user:             user._id,
    title:            `${user.name || 'User'} Weekly Workout Plan`,
    goal:             normalizeGoalLabel(user.goal),
    experienceLevel:  normalizeExperienceLabel(user.experience),
    durationWeeks:    4,
    daysPerWeek:      5,
    isAutoGenerated:  true,
    weeklyPlan,
    difficultyCoefficient: 1.0,
    generatedAt:      new Date(),
    planSource:       'ml',
    recommendationId: mlRecommendation.recommendationId ? String(mlRecommendation.recommendationId) : null,
    profileSnapshot:  {
      goal:              user.goal,
      experience:        user.experience,
      injuries:          user.injuries          || ['Regular'],
      medicalConditions: user.medicalConditions || ['Regular']
    }
  };

  await WorkoutPlan.replaceOne(filter, payload, { upsert: true });
  const updatedPlan = await WorkoutPlan.findOne(filter);

  if (!updatedPlan.weeklyPlan || updatedPlan.weeklyPlan.length !== 7) {
    throw new Error('Invalid weeklyPlan generated by ML layer');
  }

  console.log('✅ WORKOUT PLAN SAVED');
  return updatedPlan;
};

// ─── GET OR CREATE WORKOUT ───────────────────────────────────────────────────

const getOrCreateWorkoutPlan = async (user) => {
  let plan = await WorkoutPlan.findOne({ user: user._id, isAutoGenerated: true });

  const shouldRegenerate =
    !plan ||
    !Array.isArray(plan.weeklyPlan) ||
    plan.weeklyPlan.length !== 7 ||
    !plan.profileSnapshot ||
    plan.profileSnapshot.goal       !== user.goal       ||
    plan.profileSnapshot.experience !== user.experience ||
    !isArrayEqual(plan.profileSnapshot?.injuries,          user.injuries)          ||
    !isArrayEqual(plan.profileSnapshot?.medicalConditions, user.medicalConditions);

  if (shouldRegenerate) {
    console.log('♻️ Caching mismatch detected. Regenerating fresh workout plan...');
    plan = await generateAndSaveWorkoutPlan(user);
  } else {
    console.log('✅ Existing workout plan reused');
  }
  return plan;
};

