const isArrayEqual = (arr1, arr2) => {
  const a = Array.isArray(arr1) ? arr1 : (arr1 ? [arr1] : []);
  const b = Array.isArray(arr2) ? arr2 : (arr2 ? [arr2] : []);
  return JSON.stringify([...a].sort()) === JSON.stringify([...b].sort());
};

const normalizeGoal = (goal) => {
  if (!goal) return 'maintenance';
  const lower = goal.toLowerCase();
  if (lower.includes('weight')) return 'fat loss';
  if (lower.includes('muscle')) return 'muscle gain';
  return 'maintenance';
};

const normalizeGoalLabel = (goal) => {
  const normalized = normalizeGoal(goal);
  if (normalized === 'fat loss') return 'Weight Loss';
  if (normalized === 'muscle gain') return 'Muscle Gain';
  return 'Maintenance';
};

const normalizeExperience = (experience) => {
  if (!experience) return 'intermediate';
  return experience.toLowerCase();
};

const normalizeExperienceLabel = (experience) => {
  const normalized = normalizeExperience(experience);
  if (normalized === 'beginner') return 'Beginner';
  if (normalized === 'advanced') return 'Advanced';
  return 'Intermediate';
};

const normalizeActivityLevel = (activityLevel) => {
  const normalized = (activityLevel || 'moderate').toLowerCase().replace(/\s+/g, '_');
  if (['sedentary', 'light', 'moderate', 'active', 'very_active'].includes(normalized)) {
    return normalized;
  }
  if (normalized.includes('very')) return 'very_active';
  return 'moderate';
};

const normalizeDietType = (dietType) => {
  if (!dietType) return 'vegetarian';
  const d = String(dietType).toLowerCase().trim();
  if (d.includes('vegan')) return 'vegan';
  if (d.includes('non') || d.includes('meat') || d.includes('omnivore') || d.includes('non-veg') || d.includes('nonveget')) return 'non-vegetarian';
  if (d.includes('veget')) return 'vegetarian';
  return 'vegetarian';
};

const getMondayStart = (date = new Date()) => {
  const result = new Date(date);
  result.setHours(0, 0, 0, 0);
  const day = result.getDay();
  const diff = (day + 6) % 7;
  result.setDate(result.getDate() - diff);
  return result;
};

// ─── SAFE toObject HELPER ────────────────────────────────────────────────────
// Works whether the value is a Mongoose document, a Mongoose subdoc,
// or a plain JavaScript object (e.g. after .lean() or a spread).

const toPlainObject = (value) => {
  if (value === null || value === undefined) return value;
  if (typeof value.toObject === 'function') return value.toObject();
  if (typeof value === 'object') return { ...value };
  return value;
};

// ─── DIFFICULTY COEFFICIENT ──────────────────────────────────────────────────

const fetchUpdatedCoefficient = async (averageDifficulty, currentCoefficient = 1.0) => {
  try {
    const response = await axios.post(`${ML_API_URL}/scale-difficulty`, {
      average_difficulty: averageDifficulty
    }, { timeout: 4000 });
    return response.data.new_difficulty_coefficient || currentCoefficient;
  } catch (err) {
    console.warn('scale-difficulty service unavailable:', err.message);
    // Inline fallback mirrors Flask logic
    if (averageDifficulty < 4) return Math.min((currentCoefficient * 1.15), 1.5);
    if (averageDifficulty > 7) return Math.max((currentCoefficient * 0.85), 0.6);
    return currentCoefficient;
  }
};

// ─── APPLY COEFFICIENT TO A SAVED PLAN ──────────────────────────────────────

const applyDifficultyScalingToPlan = async (userId, dayIndex, averageDifficulty) => {
  const plan = await WorkoutPlan.findOne({ user: userId, isAutoGenerated: true });
  if (!plan || !Array.isArray(plan.weeklyPlan)) {
    console.warn('applyDifficultyScalingToPlan: no plan found');
    return null;
  }

  const currentCoefficient = plan.difficultyCoefficient || 1.0;
  const newCoefficient = await fetchUpdatedCoefficient(averageDifficulty, currentCoefficient);

  console.log(`📊 Difficulty rating: ${averageDifficulty} | Coefficient: ${currentCoefficient} → ${newCoefficient}`);

  // Scale sets & reps on every future, non-rest, not-yet-completed day
  const updatedWeeklyPlan = plan.weeklyPlan.map((day, idx) => {
    if (idx <= dayIndex) return day;        // past days — leave untouched
    if (day.type === 'rest') return day;    // rest days — nothing to scale
    if (day.completed) return day;          // already done — don't touch

    // ✅ FIX: Use toPlainObject() instead of day.toObject() so this works
    //         whether `day` is a Mongoose subdoc OR a plain JS object.
    const dayObj = toPlainObject(day);

    const scaledExercises = (dayObj.exercises || []).map(ex => {
      // ✅ FIX: Same safe conversion for each exercise subdoc.
      const exObj = toPlainObject(ex);
      return {
        ...exObj,
        sets: Math.max(1, Math.round((exObj.sets || 3) * newCoefficient)),
        reps: Math.max(1, Math.round((exObj.reps || 10) * newCoefficient))
      };
    });

    return { ...dayObj, exercises: scaledExercises };
  });

  plan.weeklyPlan = updatedWeeklyPlan;
  plan.difficultyCoefficient = newCoefficient;
  await plan.save();

  console.log(`✅ Difficulty scaling applied to days after index ${dayIndex}`);
  return plan;
};

